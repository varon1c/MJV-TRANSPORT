CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
    model VARCHAR(120) NOT NULL CHECK (length(trim(model)) > 0),
    category VARCHAR(60) NOT NULL DEFAULT 'van',
    description TEXT NOT NULL DEFAULT '',
    capacity SMALLINT NOT NULL CHECK (capacity BETWEEN 1 AND 100),
    rental_rate NUMERIC(12, 2) CHECK (rental_rate IS NULL OR rental_rate >= 0),
    image_path VARCHAR(250) NOT NULL DEFAULT 'images/van.png',
    availability_status VARCHAR(16) NOT NULL DEFAULT 'available'
        CHECK (availability_status IN ('available', 'unavailable')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT vehicles_name_unique UNIQUE (name)
);

CREATE INDEX vehicles_active_status ON vehicles (is_active, availability_status);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(201) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(40) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(20) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
    pickup_at TIMESTAMPTZ NOT NULL,
    return_at TIMESTAMPTZ NOT NULL,
    pickup_location VARCHAR(250) NOT NULL,
    destination VARCHAR(250) NOT NULL DEFAULT '',
    passengers SMALLINT NOT NULL CHECK (passengers BETWEEN 1 AND 100),
    special_requests VARCHAR(2000) NOT NULL DEFAULT '',
    quoted_amount NUMERIC(12, 2) CHECK (quoted_amount IS NULL OR quoted_amount >= 0),
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')),
    admin_notes VARCHAR(3000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (return_at > pickup_at)
);

CREATE INDEX bookings_vehicle_dates
    ON bookings (vehicle_id, pickup_at, return_at)
    WHERE status = 'confirmed';
CREATE INDEX bookings_status_created ON bookings (status, created_at DESC);
CREATE INDEX bookings_customer ON bookings (customer_id);

CREATE TABLE inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    subject VARCHAR(160) NOT NULL,
    message VARCHAR(5000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'in_progress', 'resolved', 'archived')),
    admin_notes VARCHAR(3000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX inquiries_status_created ON inquiries (status, created_at DESC);

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(201) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(40) NOT NULL DEFAULT '',
    position VARCHAR(120) NOT NULL,
    birthday DATE NOT NULL,
    gender VARCHAR(20) NOT NULL CHECK (gender IN ('male', 'female', 'other')),
    nationality VARCHAR(100) NOT NULL,
    birthplace VARCHAR(150) NOT NULL,
    message VARCHAR(3000) NOT NULL DEFAULT '',
    files JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'reviewing', 'shortlisted', 'rejected', 'hired')),
    admin_notes VARCHAR(3000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX applications_status_created ON applications (status, created_at DESC);
CREATE INDEX applications_email ON applications (email);

CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE admin_sessions (
    session_hash CHAR(64) PRIMARY KEY,
    admin_user_id BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
    csrf_token CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX admin_sessions_expiry ON admin_sessions (expires_at);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_username VARCHAR(64) NOT NULL,
    action VARCHAR(40) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id VARCHAR(40) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX audit_log_created ON audit_log (created_at DESC);
